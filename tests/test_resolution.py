import pytest

from ekdist.resolution import impose_resolution


# =========================================================================== #
# Input validation                                                              #
# =========================================================================== #

class TestInputValidation:
    def test_mismatched_lengths_raises(self):
        with pytest.raises(ValueError, match="same length"):
            impose_resolution(
                np.array([0.1, 0.2]), np.array([1.0]), np.array([0, 0]), tres=0.0
            )

    def test_empty_arrays_raises(self):
        with pytest.raises(ValueError, match="empty"):
            impose_resolution(
                np.array([]), np.array([]), np.array([]), tres=0.0
            )

    def test_negative_tres_raises(self):
        with pytest.raises(ValueError, match="non-negative"):
            impose_resolution(
                np.array([0.1]), np.array([1.0]), np.array([0]), tres=-1.0
            )

    def test_no_resolvable_intervals_raises(self):
        # tres larger than all intervals → nothing resolvable
        with pytest.raises(ValueError, match="No resolvable"):
            impose_resolution(
                np.array([0.001, 0.001]),
                np.array([1.0, 0.0]),
                np.array([0, 0]),
                tres=0.01,
            )

    def test_all_bad_flags_raises(self):
        with pytest.raises(ValueError, match="No resolvable"):
            impose_resolution(
                np.array([0.1, 0.05]),
                np.array([1.0, 0.0]),
                np.array([8, 8]),  # all unusable
                tres=0.001,
            )


