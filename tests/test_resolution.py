class TestKnownOutputs:
    def test_single_open_period(self, single_open_record):
        """[open 100ms, shut 50ms] → one 100ms open period after resolution."""
        itint, iampl, iprop = single_open_record
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rtint) == 1
        npt.assert_almost_equal(rtint[0], 0.1, decimal=6)
        npt.assert_almost_equal(rampl[0], 1.0, decimal=5)

    def test_two_open_periods(self, two_open_record):
        """[open, shut, open, shut] → two open periods."""
        itint, iampl, iprop = two_open_record
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rtint) == 3  # open, shut, open
        assert rampl[0] != 0
        assert rampl[1] == 0
        assert rampl[2] != 0

    def test_short_shut_between_opens_lowers_running_amplitude(
        self, short_shut_between_opens
    ):
        """A short (unresolvable) SHUT between two same-amplitude opens shifts the
        running amplitude below the tolerance, causing a period break.

        The short shut contributes 0 to the accumulated amplitude-time product
        but increases the accumulated time, so atemp/ttemp < iampl of the next
        open → |difference| > AMPLITUDE_TOLERANCE → a new open period is started.

        This is correct and faithful to the Fortran original.  The fixture uses
        iampl=[1.0, 0.0, 1.0, 0.0]; the short 0.0 interval is a SHUT so it
        dilutes the running mean → two resolved open periods.
        """
        itint, iampl, iprop = short_shut_between_opens
        tres = 0.001
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=tres)
        # Two separate open periods (not merged) because running amplitude drops
        assert len(rtint) == 2
        # Total open time is conserved (50ms + 80ms; the short 0.1ms is absorbed)
        npt.assert_almost_equal(np.sum(rtint), 0.1301, decimal=4)

    def test_short_open_between_same_amplitude_opens(self):
        """A short (unresolvable) OPEN of the same amplitude IS merged.

        When the unresolvable interval is an open (not shut), atemp also
        increases proportionally → running amplitude stays constant →
        difference <= AMPLITUDE_TOLERANCE → one merged open period.
        """
        itint = np.array([0.05, 0.0001, 0.08, 0.04])
        iampl = np.array([1.0, 1.0, 1.0, 0.0])   # all opens have amplitude 1.0
        iprop = np.array([0, 0, 0, 0])
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rtint) == 1
        npt.assert_almost_equal(rtint[0], 0.1301, decimal=4)

    def test_negative_interval_marked_bad(self):
        """Negative duration intervals must be silently marked unusable (not raise)."""
        itint = np.array([-0.001, 0.1, 0.05])
        iampl = np.array([1.0, 1.0, 0.0])
        iprop = np.array([0, 0, 0])
        # Should not raise; first interval is bad, processing starts at index 1
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rtint) >= 1

    def test_badopen_flag(self):
        """Open interval longer than badopen must be flagged BAD (flag=8)."""
        from ekdist._constants import BAD_FLAG

        itint = np.array([1.0, 0.05])   # 1 s open, 50 ms shut
        iampl = np.array([1.0, 0.0])
        iprop = np.array([0, 0])
        rtint, rampl, rprop = impose_resolution(
            itint, iampl, iprop, tres=0.001, badopen=0.5
        )
        # The 1-s open should be flagged as bad
        assert rtint[0] == pytest.approx(1.0)
        assert rprop[0] == BAD_FLAG

    def test_simulated_flag(self):
        """For simulated records amplitude handling differs; must not raise."""
        itint = np.array([0.05, 0.0001, 0.08, 0.04])
        iampl = np.array([1.0, 0.0, 1.0, 0.0])
        iprop = np.array([0, 0, 0, 0])
        rtint, rampl, rprop = impose_resolution(
            itint, iampl, iprop, tres=0.001, is_simulated=True
        )
        assert len(rtint) >= 1


