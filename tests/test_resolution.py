class TestAChSimStructural:
    """Structural properties that must hold for the AChsim.scn dataset.

    TODO: Replace with exact numeric regression once Fortran reference outputs
    are available (see module docstring TODO).
    """

    def test_resolved_count_less_than_raw(self, loaded_record):
        assert len(loaded_record.rtint) < len(loaded_record.itint)

    def test_starts_with_open(self, loaded_record):
        assert loaded_record.rampl[0] != 0.0

    def test_ends_with_open(self, loaded_record):
        assert loaded_record.rampl[-1] != 0.0

    def test_no_trailing_shuts(self, loaded_record):
        assert loaded_record.rampl[-1] != 0.0

    def test_periods_count_less_than_resolved(self, loaded_record):
        assert len(loaded_record.periods.intervals) <= len(loaded_record.rtint)

    def test_periods_alternates_open_shut(self, loaded_record):
        amps = loaded_record.periods.amplitudes
        for i in range(len(amps) - 1):
            is_open_i = amps[i] != 0
            is_open_next = amps[i + 1] != 0
            assert is_open_i != is_open_next, (
                f"Periods must alternate open/shut; failed at index {i}"
            )


