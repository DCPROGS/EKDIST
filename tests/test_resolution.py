# Structural properties (hold for any valid record)                            #
# =========================================================================== #

class TestStructuralProperties:
    def test_result_starts_with_open(self, simple_intervals):
        itint, iampl, iprop = simple_intervals
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rampl) > 0
        assert rampl[0] != 0.0, "First resolved interval must be an opening"

    def test_result_ends_with_open(self, simple_intervals):
        itint, iampl, iprop = simple_intervals
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert rampl[-1] != 0.0, "Last resolved interval must be an opening"

    def test_no_negative_durations(self, simple_intervals):
        itint, iampl, iprop = simple_intervals
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert np.all(rtint >= 0), "All resolved durations must be non-negative"

    def test_resolution_reduces_interval_count(self):
        """After tres > 0, resolved count must be < raw count."""
        itint = np.array([0.05, 0.0005, 0.08, 0.04])
        iampl = np.array([1.0, 0.0, 1.0, 0.0])
        iprop = np.array([0, 0, 0, 0])
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.001)
        assert len(rtint) <= len(itint)

    def test_zero_resolution_preserves_structure(self):
        """tres=0 should resolve all intervals (none concatenated)."""
        itint = np.array([0.05, 0.02, 0.08, 0.03])
        iampl = np.array([1.0, 0.0, 1.0, 0.0])
        iprop = np.array([0, 0, 0, 0])
        rtint, rampl, rprop = impose_resolution(itint, iampl, iprop, tres=0.0)
        # Two opens, two shuts; after trimming trailing shut: 3 resolved
        assert len(rtint) == 3
        assert rampl[0] != 0.0
        assert rampl[1] == 0.0
        assert rampl[2] != 0.0


