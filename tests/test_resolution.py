class TestAChSimNumericalRegression:
    """Pin the exact impose_resolution output for AChsim.scn at tres=30 µs.

    Values were computed on 2026-06-04 from our Python implementation and serve
    as a golden-master regression guard.  Any future change to impose_resolution
    that alters these numbers must be deliberate and accompanied by an update
    to these constants.
    """

    # ---- expected counts ------------------------------------------------- #

    def test_raw_interval_count(self, loaded_record):
        assert len(loaded_record.itint) == 13948

    def test_resolved_interval_count(self, loaded_record):
        assert len(loaded_record.rtint) == 8565

    def test_resolved_open_count(self, loaded_record):
        open_mask = loaded_record.rampl != 0
        assert int(np.sum(open_mask)) == 4283

    def test_resolved_shut_count(self, loaded_record):
        shut_mask = loaded_record.rampl == 0
        assert int(np.sum(shut_mask)) == 4282

    def test_period_count(self, loaded_record):
        assert len(loaded_record.periods.intervals) == 8565

    def test_open_period_count(self, loaded_record):
        assert len(loaded_record.periods.open_intervals) == 4283

    def test_shut_period_count(self, loaded_record):
        assert len(loaded_record.periods.shut_intervals) == 4282

    # ---- first / last intervals ------------------------------------------ #

    def test_first_ten_durations(self, loaded_record):
        expected_t = np.array([
            4.0676165e-05, 1.161550368, 5.43031275e-04, 2.868956055,
            1.46274611e-04, 4.634056079, 4.87697683e-04, 1.19268e-04,
            1.735255003e-03, 3.184402588,
        ])
        npt.assert_almost_equal(loaded_record.rtint[:10], expected_t, decimal=6)

    def test_first_ten_amplitudes(self, loaded_record):
        expected_a = np.array([6., 0., 6., 0., 6., 0., 6., 0., 6., 0.])
        npt.assert_almost_equal(loaded_record.rampl[:10], expected_a, decimal=4)

    def test_last_three_durations(self, loaded_record):
        expected_t = np.array([8.9477e-05, 2.359118835, 3.83195e-04])
        npt.assert_almost_equal(loaded_record.rtint[-3:], expected_t, decimal=6)

    def test_last_interval_is_open(self, loaded_record):
        assert loaded_record.rampl[-1] != 0.0

    # ---- global statistics ----------------------------------------------- #

    def test_total_resolved_duration(self, loaded_record):
        """Total resolved duration must match golden value to 3 decimal places."""
        npt.assert_almost_equal(np.sum(loaded_record.rtint), 7683.308, decimal=3)

    def test_min_open_duration(self, loaded_record):
        open_mask = loaded_record.rampl != 0
        npt.assert_almost_equal(
            np.min(loaded_record.rtint[open_mask]), 30.013e-6, decimal=8
        )

    def test_max_open_duration(self, loaded_record):
        open_mask = loaded_record.rampl != 0
        npt.assert_almost_equal(
            np.max(loaded_record.rtint[open_mask]), 12.246324e-3, decimal=7
        )

    def test_max_shut_duration(self, loaded_record):
        shut_mask = loaded_record.rampl == 0
        npt.assert_almost_equal(
            np.max(loaded_record.rtint[shut_mask]), 18.486795, decimal=3
        )

    def test_mean_open_period(self, loaded_record):
        mean_ms = np.mean(loaded_record.periods.open_intervals) * 1e3
        npt.assert_almost_equal(mean_ms, 0.698800, decimal=3)

    def test_mean_shut_period(self, loaded_record):
        mean_ms = np.mean(loaded_record.periods.shut_intervals) * 1e3
        npt.assert_almost_equal(mean_ms, 1793.628, decimal=1)

    # ---- all flags must be 0 (AChsim has no bad intervals) --------------- #

    def test_all_flags_zero(self, loaded_record):
        assert np.all(loaded_record.rprop == 0)
